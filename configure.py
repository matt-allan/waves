"""Generate the build.ninja file for waves."""

import argparse
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), 'vendor', 'ninja'))
import ninja_syntax

parser = argparse.ArgumentParser(description='Configure the waves build.')
parser.add_argument('--debug', action='store_true',
                    help='enable debug flags')
parser.add_argument('--gbdk-home', default='tools/gbdk/',
                    help='path to GBDK installation (default: tools/gbdk/)')

args = parser.parse_args()

BUILD_FILENAME = 'build.ninja'
buildfile = open(BUILD_FILENAME, 'w')
n = ninja_syntax.Writer(buildfile)

n.comment('This file is generated by configure.py -- do not edit.')
n.comment('To regenerate: python3 configure.py')
n.newline()

# Regenerate build.ninja when configure.py or ninja_syntax.py changes.
n.variable('configure_args', ' '.join(sys.argv[1:]))
n.rule('configure',
       command='${python} configure.py ${configure_args}',
       generator=True,
       description='configure ${configure_args}')
n.build('build.ninja', 'configure',
        implicit=['configure.py', 'vendor/ninja/ninja_syntax.py'])
n.newline()

n.variable('python', sys.executable)

# --- ROM toolchain ---

gbdk_home = args.gbdk_home
if not gbdk_home.endswith('/'):
    gbdk_home += '/'

n.variable('gbdk_home', gbdk_home)
n.variable('cc', '${gbdk_home}bin/lcc')
n.variable('romusage', '${gbdk_home}bin/romusage')

cflags = ['-Wa-l', '-Wl-m', '-Wl-j', '-msm83:gb']
if args.debug:
    cflags += ['-debug', '-v']
n.variable('cflags', cflags)
n.newline()

n.rule('cc_gb',
       command='$cc $cflags -c -o $out $in',
       description='CC $out')
n.newline()

n.rule('link_gb',
       command='$cc $cflags -o $out $in && $romusage $mapfile',
       description='LINK $out')
n.newline()

# --- ROM build edges ---

game = 'waves'

n.build('waves.o', 'cc_gb', 'waves.c',
        implicit=['waves.h', 'envelope.h', 'protocol.h'])
n.build('envelope.o', 'cc_gb', 'envelope.c',
        implicit=['envelope.h'])
n.newline()

n.build(game + '.gb', 'link_gb', ['waves.o', 'envelope.o'],
        variables={'mapfile': game + '.map'})
n.newline()

n.default(game + '.gb')
n.newline()

# --- Test toolchain ---

sameboy_root = 'vendor/SameBoy'
sameboy_lib = os.path.join(sameboy_root, 'build', 'lib', 'libsameboy.a')
sameboy_inc = os.path.join(sameboy_root, 'build', 'include')

n.variable('test_cc', 'gcc')
n.variable('test_cflags', '-std=c11 -Wall -Wextra -I' + sameboy_inc +
           ' -Itest -I.')
n.variable('test_ldflags', '-lm')
n.newline()

n.rule('cc_host',
       command='$test_cc $test_cflags -c $in -o $out',
       description='CC $out')
n.newline()

n.rule('link_host',
       command='$test_cc $in $test_ldflags -o $out',
       description='LINK $out')
n.newline()

# SameBoy is built by its own Makefile; treat it as an external dependency.
tools_dir = os.path.abspath('tools')
n.rule('sameboy',
       command='PATH="' + tools_dir +
               ':$$PATH" make -C ' + sameboy_root +
               ' headers lib CONF=release',
       description='MAKE SameBoy',
       generator=True)
n.build(sameboy_lib, 'sameboy')
n.newline()

# --- Test build edges ---

n.build('test/harness.o', 'cc_host', 'test/harness.c',
        implicit=['test/harness.h'],
        order_only=[sameboy_lib])
n.build('test/test_basic.o', 'cc_host', 'test/test_basic.c',
        implicit=['test/harness.h', 'protocol.h'],
        order_only=[sameboy_lib])
n.newline()

n.build('test/test_basic', 'link_host',
        ['test/test_basic.o', 'test/harness.o', sameboy_lib])
n.newline()

n.close()
print('wrote %s.' % BUILD_FILENAME)
